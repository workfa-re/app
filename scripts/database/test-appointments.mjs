// Runs only against an ephemeral, in-memory PostgreSQL instance. Never accepts a database URL.
// Install the test engine outside the repository and set WORKFARE_PGLITE_MODULE to its entrypoint.
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
const modulePath = process.env.WORKFARE_PGLITE_MODULE;
if (!modulePath || !path.isAbsolute(modulePath)) throw new Error("Set WORKFARE_PGLITE_MODULE to an externally installed @electric-sql/pglite/dist/index.js.");
const { PGlite } = await import(pathToFileURL(modulePath).href);
const db = new PGlite();
const ids = Object.fromEntries(["provider", "seeker", "outsider", "job", "application", "engagement", "appointment", "second", "job2", "application2", "engagement2", "appointment2"].map((name, i) => [name, `00000000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`]));
const fixture = `
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
GRANT USAGE ON SCHEMA public, auth TO authenticated;
CREATE TABLE profiles (id uuid PRIMARY KEY);
CREATE TABLE jobs(id uuid PRIMARY KEY,title text,posted_by uuid,status text,filled_by uuid,filled_at timestamptz,completed_at timestamptz,updated_at timestamptz,job_kind text);
CREATE TABLE applications(id uuid PRIMARY KEY,job_id uuid,user_id uuid,status text,is_primary boolean,conversation_state text,rejection_reason text,updated_at timestamptz,closed_from_status text,closed_by uuid,closed_at timestamptz,closed_reason text,close_action text,was_primary_before_close boolean,closure_version integer DEFAULT 0);
CREATE TABLE job_engagements(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),application_id uuid UNIQUE,job_id uuid,provider_id uuid,seeker_id uuid,engagement_type text,status text,started_at timestamptz,completed_at timestamptz,cancelled_at timestamptz,closed_by uuid,close_reason text,updated_at timestamptz DEFAULT now());
CREATE TABLE job_appointments(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),engagement_id uuid,starts_at timestamptz,ends_at timestamptz,timezone text DEFAULT 'Europe/Berlin',note text,status text DEFAULT 'scheduled',created_by uuid,updated_at timestamptz DEFAULT now());
CREATE TABLE job_agreements(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),application_id uuid UNIQUE,job_id uuid,provider_id uuid,seeker_id uuid,starts_at timestamptz,ends_at timestamptz,timezone text,note text,status text,updated_at timestamptz DEFAULT now());
CREATE TABLE messages(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),application_id uuid,sender_id uuid,content text,kind text);
CREATE TABLE application_events(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),application_id uuid,actor_id uuid,event_type text,reason text,metadata jsonb);
CREATE TABLE notifications(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,type text,title text,body text,data jsonb);
GRANT SELECT ON job_engagements TO authenticated;
`;
let assertions = 0;
const check = (value, expected, message) => { assert.deepEqual(value, expected, message); assertions++; };
const future = days => new Date(Date.now() + days * 86400_000).toISOString();
const count = async table => Number((await db.query(`SELECT count(*) AS n FROM ${table}`)).rows[0].n);
async function as(user) {
  await db.exec("RESET ROLE");
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [user ?? ""]);
  await db.exec("SET ROLE authenticated");
}
async function manage(action, options = {}) {
  const result = await db.query("SELECT public.manage_job_appointment($1,$2,$3,$4,$5,$6,$7) AS result", [options.application ?? ids.application, action, options.appointment ?? null, options.start ?? null, options.end ?? null, options.note ?? null, options.request ?? null]);
  return result.rows[0].result;
}
try {
  await db.exec(fixture);
  const existing = await readFile(new URL("../../infrastructure/demo/schema/platform.sql", import.meta.url), "utf8");
  const confirm = existing.match(/CREATE OR REPLACE FUNCTION "public"\."confirm_job_engagement"[\s\S]*?\n\$\$;/)?.[0];
  assert.ok(confirm, "uses the actual existing initial scheduling function");
  await db.exec(confirm);
  await db.exec(await readFile(new URL("../../infrastructure/database/migrations/20261022181830_appointment_requests.sql", import.meta.url), "utf8"));
  await db.query("INSERT INTO profiles VALUES ($1),($2),($3)", [ids.provider, ids.seeker, ids.outsider]);
  for (const suffix of ["", "2"]) {
    await db.query("INSERT INTO jobs(id,title,posted_by,status,filled_by,job_kind) VALUES($1,'Garden',$2,'filled',$3,$4)", [ids[`job${suffix}`], ids.provider, ids.seeker, suffix ? "recurring" : "one_time"]);
    await db.query("INSERT INTO applications(id,job_id,user_id,status,is_primary,conversation_state) VALUES($1,$2,$3,'accepted',true,'open')", [ids[`application${suffix}`], ids[`job${suffix}`], ids.seeker]);
    await db.query("INSERT INTO job_engagements(id,application_id,job_id,provider_id,seeker_id,engagement_type,status) VALUES($1,$2,$3,$4,$5,$6,'active')", [ids[`engagement${suffix}`], ids[`application${suffix}`], ids[`job${suffix}`], ids.provider, ids.seeker, suffix ? "recurring" : "one_time"]);
    await db.query("INSERT INTO job_appointments(id,engagement_id,starts_at,note) VALUES($1,$2,$3,'Existing')", [ids[`appointment${suffix}`], ids[`engagement${suffix}`], future(2)]);
    await db.query("INSERT INTO job_agreements(application_id,starts_at,status,note) VALUES($1,$2,'confirmed','Existing')", [ids[`application${suffix}`], future(2)]);
  }
  await as(null);
  check((await manage("propose", { start: future(3) })).ok, false, "no anonymous auth context");
  await as(ids.outsider);
  check((await manage("propose", { start: future(3) })).ok, false, "outsider cannot propose");
  await as(ids.seeker);
  check((await manage("update", { appointment: ids.appointment, start: future(3) })).ok, false, "seeker cannot directly change binding appointment");
  check((await manage("propose", { appointment: ids.appointment, start: future(-1) })).ok, false, "past request refused");
  check((await manage("propose", { appointment: ids.appointment, start: future(3), end: future(2) })).ok, false, "invalid end refused");
  check((await manage("propose", { appointment: ids.appointment2, start: future(3) })).ok, false, "foreign appointment refused");
  check((await manage("propose", { start: future(3) })).ok, false, "one-time job cannot accumulate appointments");
  let request = await manage("propose", { appointment: ids.appointment, start: future(3), end: future(3.05), note: "Please later" });
  check(request.ok, true, "seeker proposal persisted");
  check(request.appointment, null, "proposal does not return an unassigned appointment record");
  check((await manage("propose", { appointment: ids.appointment, start: future(4) })).ok, false, "one pending proposal per conversation");
  check((await manage("accept", { request: request.request.id })).ok, false, "requester cannot accept own request");
  await db.exec("RESET ROLE");
  check(await count("job_appointment_requests"), 1, "request stored in database");
  check((await db.query("SELECT note FROM job_appointments WHERE id=$1", [ids.appointment])).rows[0].note, "Existing", "proposal leaves old binding appointment unchanged");
  await as(ids.outsider);
  check((await db.query("SELECT id FROM job_appointment_requests")).rows.length, 0, "RLS hides requests from outsiders");
  await as(ids.provider);
  check((await db.query("SELECT id FROM job_appointment_requests")).rows.length, 1, "RLS permits participant request read");
  await assert.rejects(db.query("UPDATE job_appointment_requests SET status='accepted'"), /permission denied/); assertions++;
  check((await manage("withdraw", { request: request.request.id })).ok, false, "provider cannot withdraw seeker request");
  check((await manage("decline", { request: request.request.id })).request.status, "declined", "provider can decline without appointment mutation");
  await as(ids.seeker);
  request = await manage("propose", { appointment: ids.appointment, start: future(4), note: "New date" });
  await as(ids.provider);
  let result = await manage("accept", { request: request.request.id });
  check(result.ok, true, "provider accepts proposal");
  check(result.appointment.note, "New date", "acceptance applies persisted proposal not caller input");
  check(result.request.status, "accepted", "request resolved atomically");
  check((await manage("accept", { request: request.request.id })).ok, false, "resolved request cannot replay");
  await as(ids.seeker);
  request = await manage("propose", { appointment: ids.appointment, start: future(5) });
  check((await manage("withdraw", { request: request.request.id })).request.status, "withdrawn", "requester can withdraw");
  request = await manage("propose", { appointment: ids.appointment, start: future(6) });
  await as(ids.provider);
  check((await manage("update", { appointment: ids.appointment, start: future(7), note: "Provider update" })).ok, true, "provider directly edits appointment");
  check((await manage("accept", { request: request.request.id })).ok, false, "provider edit supersedes obsolete request");
  await as(ids.seeker);
  request = await manage("propose", { appointment: ids.appointment, start: future(8) });
  await db.exec("RESET ROLE");
  await db.query("UPDATE job_appointments SET updated_at=updated_at+interval '1 second' WHERE id=$1", [ids.appointment]);
  await as(ids.provider);
  check((await manage("accept", { request: request.request.id })).ok, false, "legacy/concurrent changes make request stale");
  await as(ids.seeker);
  await manage("withdraw", { request: request.request.id });
  await as(ids.provider);
  check((await manage("cancel", { appointment: ids.appointment })).appointment.status, "cancelled", "provider cancels only appointment");
  await db.exec("RESET ROLE");
  check((await db.query("SELECT status FROM applications WHERE id=$1", [ids.application])).rows[0].status, "accepted", "cancellation keeps collaboration accepted");
  check((await db.query("SELECT status FROM job_agreements WHERE application_id=$1", [ids.application])).rows[0].status, "cancelled", "legacy agreement cannot retain cancelled time");
  await as(ids.provider);
  result = await manage("add", { start: future(9) });
  check(result.ok, true, "new one-time appointment possible after cancellation");
  await as(ids.seeker);
  request = await manage("propose", { application: ids.application2, start: future(4), note: "Extra recurring date" });
  check(request.ok, true, "recurring collaboration permits additional appointment proposal");
  await as(ids.provider);
  result = await manage("accept", { application: ids.application2, request: request.request.id });
  check(result.ok, true, "additional recurring appointment accepted via actual confirm_job_engagement");
  check(result.appointment.note, "Extra recurring date", "new appointment is persisted");
  await db.exec("RESET ROLE");
  check(Number((await db.query("SELECT count(*) n FROM job_appointments WHERE engagement_id=$1 AND status='scheduled'", [ids.engagement2])).rows[0].n), 2, "recurring creation preserves earlier appointment");
  await as(ids.seeker);
  request = await manage("propose", { application: ids.application2, start: future(8) });
  await db.exec("RESET ROLE");
  await db.query("UPDATE applications SET conversation_state='closed' WHERE id=$1", [ids.application2]);
  check((await db.query("SELECT status FROM job_appointment_requests WHERE id=$1", [request.request.id])).rows[0].status, "superseded", "closing a conversation retires pending requests before reopening");
  await db.query("UPDATE applications SET conversation_state='closed' WHERE id=$1", [ids.application]);
  await as(ids.provider);
  check((await manage("update", { appointment: result.appointment.id, start: future(10) })).ok, false, "closed collaborations immutable");
  await db.exec("RESET ROLE");
  check((await db.query("SELECT prosecdef FROM pg_proc WHERE oid='public.manage_job_appointment(uuid,text,uuid,timestamptz,timestamptz,text,uuid)'::regprocedure")).rows[0].prosecdef, false, "exposed RPC is security invoker");
  check((await db.query("SELECT has_function_privilege('anon','public.manage_job_appointment(uuid,text,uuid,timestamptz,timestamptz,text,uuid)','EXECUTE') AS allowed")).rows[0].allowed, false, "anonymous execute revoked");
  console.log(`Appointment migration: ${assertions} PostgreSQL assertions passed. No network database or production writes.`);
} finally { await db.close(); }
